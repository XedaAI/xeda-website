const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const languageLabels: Record<SiteLanguage, { name: string; flag: string }> = {
  en: { name: "English", flag: "🇬🇧" },
  de: { name: "Deutsch", flag: "🇩🇪" },
  fr: { name: "Français", flag: "🇫🇷" },
  es: { name: "Español", flag: "🇪🇸" },
  it: { name: "Italiano", flag: "🇮🇹" },
};

const supportedLanguages: SiteLanguage[] = ["en", "de", "fr", "es", "it"];

const detectBrowserLanguage = (): SiteLanguage => {
  const browserLang = navigator.language.split("-")[0].toLowerCase();
  if (supportedLanguages.includes(browserLang as SiteLanguage)) {
    return browserLang as SiteLanguage;
  }
  return "en";
};

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<SiteLanguage>(() => {
    const saved = localStorage.getItem("site_language");
    if (saved && supportedLanguages.includes(saved as SiteLanguage)) {
      return saved as SiteLanguage;
    }
    // Auto-detect from browser if no saved preference
    return detectBrowserLanguage();
  });

  useEffect(() => {
    localStorage.setItem("site_language", language);
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (lang: SiteLanguage) => {
    setLanguageState(lang);
  };

  const t = (key: string): string => {
    return translations[language][key] || translations.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
